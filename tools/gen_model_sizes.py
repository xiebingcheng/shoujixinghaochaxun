def guess(text):
    k = norm(text)
    if k in PLACEHOLDERS:
        return None
    fold = fold_value(text)
    if fold is not None:
        return fold_entry(*fold)
    for prefix, inch in PREFIX_RULES:
        if k.startswith(prefix):
            return inch
    if k in EXACT_RULES:
        return EXACT_RULES[k]
    return None


def main():
    merge = "--merge" in sys.argv
    with open(BOXES_PATH, encoding="utf-8") as f:
        data = json.load(f)

    existing = {}
    if merge and os.path.exists(OUT_PATH):
        with open(OUT_PATH, encoding="utf-8") as f:
            existing = (json.load(f).get("models") or {})

    models = {}
    seen = set()
    hit = miss = 0
    for box in data["boxes"]:
        for m in box["models"]:
            t = m["t"]
            key = norm(t)
            if key in seen:
                continue
            seen.add(key)
            # 折叠屏 / 占位词优先处理，折叠屏即使已有旧数值也要用最新的内屏外屏覆盖
            fold = fold_value(t)
            if fold is not None:
                models[t] = fold_entry(*fold)
                hit += 1
                continue
            if key in PLACEHOLDERS:
                continue
            if t in existing:
                models[t] = existing[t]
                hit += 1
                continue
            inch = guess(t)
            if inch is None:
                miss += 1
                continue
            models[t] = inch
            hit += 1

    payload = {
        "note": "手机型号 -> 屏幕尺寸（英寸）。型号写法随意，脚本会按网站同一套规则归一化。"
                "这里是自动生成的初版（tools/gen_model_sizes.py），数值还没人工核对；"
                "发现不对就直接改本文件，改完运行 python tools/build_sizes.py。",
        "models": dict(sorted(models.items(), key=lambda kv: kv[0].lower())),
    }
    with open(OUT_PATH, "w", encoding="utf-8") as f:
        json.dump(payload, f, ensure_ascii=False, indent=2)
        f.write("\n")
    total = hit + miss
    print(f"[OK] {OUT_PATH}")
    print(f"     写入 {len(models)} 条（命中 {hit} / {total}，未命中 {miss}，"
          f"覆盖 {100 * hit / total:.1f}%）")


if __name__ == "__main__":
    main()
